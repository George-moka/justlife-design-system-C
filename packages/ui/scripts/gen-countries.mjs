/**
 * Generate the country dataset for the phone-number country picker.
 *
 *   node packages/ui/scripts/gen-countries.mjs
 *
 * Source (build-time devDeps only — NOT runtime):
 *   - world-countries  → ISO2 (cca2), common name, dial code (idd.root + suffix)
 *   - country-flag-icons → 3x2 SVG flag string per ISO
 *
 * Output: packages/ui/src/data/countries.generated.ts — a self-contained, committed data file
 * (each entry inlines its flag SVG), so the app ships with NO new runtime dependency.
 * UAE + KSA are pinned to the top (Justlife's primary markets); the rest are alphabetical.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPTS = path.dirname(fileURLToPath(import.meta.url));
const UI = path.resolve(SCRIPTS, '..');
const NM = path.join(UI, 'node_modules');
const FLAG_DIR = path.join(NM, 'country-flag-icons/string/3x2');
const PINNED = ['AE', 'SA', 'OM', 'QA', 'BH']; // GCC, surfaced first in this order (matches the live app)

const dialOf = (c) => {
  const root = c.idd?.root;
  const suffixes = c.idd?.suffixes ?? [];
  if (!root) return null;
  // One suffix → a unique code (AE: +9 / 71 → +971). Many suffixes → a shared code (US/CA: +1).
  return suffixes.length === 1 ? root + suffixes[0] : root;
};

const flagOf = async (iso) => {
  try {
    const src = await fs.readFile(path.join(FLAG_DIR, `${iso}.js`), 'utf8');
    return src.match(/export default '([\s\S]*?)';?\s*$/)?.[1] ?? null;
  } catch {
    return null; // no flag asset for this territory → skip it
  }
};

const wc = JSON.parse(await fs.readFile(path.join(NM, 'world-countries/countries.json'), 'utf8'));

const rows = [];
for (const c of wc) {
  const iso2 = c.cca2;
  const dial = dialOf(c);
  if (!dial) continue;
  const flag = await flagOf(iso2);
  if (!flag) continue;
  rows.push({ iso2, name: c.name.common, dial, flag });
}

rows.sort((a, b) => {
  const pa = PINNED.indexOf(a.iso2);
  const pb = PINNED.indexOf(b.iso2);
  if (pa !== -1 && pb !== -1) return pa - pb;
  if (pa !== -1) return -1;
  if (pb !== -1) return 1;
  return a.name.localeCompare(b.name);
});

const file =
  `// AUTO-GENERATED by scripts/gen-countries.mjs — do not edit by hand.\n` +
  `// Source: world-countries (data) + country-flag-icons (3x2 SVG). Regenerate: node scripts/gen-countries.mjs\n` +
  `// ${rows.length} countries; UAE + KSA pinned first, then alphabetical. Flags inlined → no runtime dep.\n\n` +
  `export interface Country {\n  /** ISO 3166-1 alpha-2, e.g. "AE". */\n  iso2: string;\n  /** Common English name. */\n  name: string;\n  /** Dial code incl. "+", e.g. "+971". */\n  dial: string;\n  /** 3x2 flag as an inline SVG string (render with react-native-svg \`SvgXml\`). */\n  flag: string;\n}\n\n` +
  `export const COUNTRIES: Country[] = ${JSON.stringify(rows)};\n\n` +
  `/** How many leading entries are pinned (GCC) — render a separator after them in the picker. */\n` +
  `export const PINNED_COUNT = ${PINNED.filter((iso) => rows.some((r) => r.iso2 === iso)).length};\n`;

const outPath = path.join(UI, 'src/data/countries.generated.ts');
await fs.mkdir(path.dirname(outPath), { recursive: true });
await fs.writeFile(outPath, file);
console.log(`✓ wrote ${rows.length} countries → ${path.relative(process.cwd(), outPath)} (${(file.length / 1024).toFixed(0)} KB)`);
